import { createContext, useContext, useMemo, useState, type ReactNode } from 'react';
import { initialAlerts, initialEvents, initialIncidents } from '../lib/mockData';
import type { Incident, SecurityAlert, SecurityEvent } from '../types/security';

interface SecurityContextValue {
  events: SecurityEvent[];
  alerts: SecurityAlert[];
  incidents: Incident[];
  addDemoBurst: () => void;
  updateAlertStatus: (id: string, status: SecurityAlert['status']) => void;
  updateIncidentStatus: (id: string, status: Incident['status']) => void;
}
const SecurityContext = createContext<SecurityContextValue | null>(null);
export function SecurityProvider({ children }: { children: ReactNode }) {
  const [events, setEvents] = useState(initialEvents);
  const [alerts, setAlerts] = useState(initialAlerts);
  const [incidents, setIncidents] = useState(initialIncidents);
  const addDemoBurst = () => {
    const now = new Date().toISOString();
    const burst: SecurityEvent[] = Array.from({ length: 4 }, (_, i) => ({
      id: `EVT-${Math.floor(90000 + Math.random() * 999) + i}`,
      timestamp: new Date(Date.now() - i * 12000).toISOString(),
      sourceIp: '198.51.100.42', source: 'auth-gateway-01', eventType: 'Authentication',
      actor: 'demo-user@sentinel.local', target: '/api/auth/login', severity: i === 0 ? 'High' : 'Medium',
      outcome: 'Failed', summary: 'Demo failed sign-in event generated by analyst simulation',
    }));
    setEvents(current => [...burst, ...current]);
    setAlerts(current => [{
      id: `ALT-${Math.floor(3000 + Math.random() * 900)}`, title: 'Authentication failure burst (demo)', severity: 'High', status: 'New', sourceIp: '198.51.100.42', firstSeen: now, eventCount: burst.length, rule: 'AUTH-004 · Repeated authentication failures', description: 'A simulated burst of failed sign-in events was generated locally to demonstrate triage workflows.', evidence: ['4 failed sign-in events generated by the demo action', 'Source address is reserved for documentation', 'No external system was contacted'], assignee: 'Unassigned'
    }, ...current]);
  };
  const updateAlertStatus = (id: string, status: SecurityAlert['status']) => setAlerts(current => current.map(alert => alert.id === id ? { ...alert, status } : alert));
  const updateIncidentStatus = (id: string, status: Incident['status']) => setIncidents(current => current.map(incident => incident.id === id ? { ...incident, status, updatedAt: new Date().toISOString() } : incident));
  const value = useMemo(() => ({ events, alerts, incidents, addDemoBurst, updateAlertStatus, updateIncidentStatus }), [events, alerts, incidents]);
  return <SecurityContext.Provider value={value}>{children}</SecurityContext.Provider>;
}
export function useSecurityData() {
  const context = useContext(SecurityContext);
  if (!context) throw new Error('useSecurityData must be used inside SecurityProvider');
  return context;
}
